import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base=process.env.BASE_URL||'http://127.0.0.1:5175';
const browser=await chromium.launch({headless:true});
try {
  const page=await browser.newPage({reducedMotion:'reduce'});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  const order=['KNN','TREE','LOGREG','COMPARE','TEACHABLE','LINREG','KMEANS','PCA','FOREST','SVM'];
  assert.deepEqual(await page.locator('.catalog-group-ml h4 a').evaluateAll(nodes=>nodes.map(n=>n.id.replace('lesson-',''))),order);
  assert.deepEqual(await page.locator('.catalog-group-ml .lesson-level').allTextContents(),order.map((id,i)=>`${String(i+1).padStart(2,'0')} · ${i<5?'Cơ bản':'Mở rộng · Tùy chọn'}`));
  await page.locator('#filter-ml').click();
  await page.locator('#home-search').fill('PCA');
  assert.match(await page.locator('.lesson-level').innerText(),/^08/);
  await page.goto(`${base}/#/datasets`);
  const csv='patient_id,length,width,site,label\n'+Array.from({length:60},(_,i)=>`${i},${i+1},${i%10+3},${i%3?'A':'B'},${i%2?'yes':'no'}`).join('\n');
  await page.getByLabel('Chọn file dữ liệu',{exact:true}).setInputFiles({name:'measurements.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
  await page.getByRole('button',{name:'Dùng dữ liệu này',exact:true}).click();
  await expect(page.locator('.data-fit')).toContainText('measurements.csv');
  await expect(page.locator('.data-fit')).toContainText('patient_id');
  await page.goto(`${base}/#/ml/knn?tab=lab`);
  await expect(page.locator('.medical-case')).toContainText('length');
  await expect(page.locator('.medical-case')).not.toContainText('glucose/BMI');
  await expect(page.locator('#journal-KNN-0').locator('..')).toContainText('label');
  await page.goto(`${base}/#/ml/knn?tab=theory`);
  await page.locator('#download-uploaded-notebook').waitFor();
  let pending=page.waitForEvent('download');
  await page.locator('#download-uploaded-notebook').click();
  let file=await pending;
  assert.equal(file.suggestedFilename(),'knn-du-lieu-cua-ban.ipynb');
  const book=JSON.parse(await fs.readFile(await file.path(),'utf8'));
  const code=book.cells.filter(c=>c.cell_type==='code').map(c=>c.source.join('')).join('\n');
  assert.match(code,/NUMERIC = \["length","width"\]/);
  assert.match(code,/CATEGORICAL = \["site"\]/);
  assert.match(code,/GROUP_COLUMN = None/);
  assert.ok(!code.includes('patient_id,length,width,site,label'));
  pending=page.waitForEvent('download');
  await page.locator('#download-session-csv').click();
  file=await pending;
  assert.match(await fs.readFile(await file.path(),'utf8'),/"patient_id","length","width","site","label"/);
  for(const [width,height] of [[1440,900],[768,1024],[390,844]]){
    await page.setViewportSize({width,height});
    await page.locator('.uploaded-notebook').scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:`/tmp/adaptive-notebook-${width}.png`});
  }
  await page.goto(`${base}/#/dl/cnn?tab=theory`);
  await expect(page.locator('.data-fit')).toContainText('mô phỏng riêng');
  assert.equal(await page.locator('#download-uploaded-notebook').count(),0);
  await page.goto(`${base}/#/datasets`);
  const text='note\n'+Array.from({length:40},(_,i)=>`Only words row ${i}`).join('\n');
  await page.getByLabel('Chọn file dữ liệu',{exact:true}).setInputFiles({name:'text.csv',mimeType:'text/csv',buffer:Buffer.from(text)});
  await page.getByRole('button',{name:'Dùng dữ liệu này',exact:true}).click();
  await page.goto(`${base}/#/ml/knn?tab=lab`);
  await expect(page.locator('.data-fit')).toContainText('Chưa có cột nhãn');
  assert.deepEqual(errors,[]);
  console.log('PASS explicit ML order, stable numbering under search, uploaded-data guidance, compatibility, schema-only notebook, CSV snapshot, 3 viewports, no page errors.');
} finally {await browser.close();}
