import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

import { BASE_URL as base } from './browser.config.mjs';
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [], failed = [], external = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) failed.push(r.url()); });
  page.on('request', r => { if (r.url().startsWith('http') && !r.url().startsWith(base)) external.push(r.url()); });
  let dismissNavigation = false;
  page.on('dialog', dialog => dismissNavigation ? dialog.dismiss() : dialog.accept());
  await page.goto(base);
  await page.locator('#home-open-station').click();
  await expect(page.locator('h1')).toHaveText('Trạm Tin học Y khoa');
  await expect(page.locator('.station-group')).toHaveCount(6);
  for (const [group, count] of [['start', 3], ['python', 1], ['data', 3], ['ml', 11], ['dl', 10], ['genai', 3]]) {
    await page.locator(`#station-group-${group}`).click();
    await expect(page.locator('.station-resources li')).toHaveCount(count);
    await expect(page.locator('#station-plan-group')).toHaveAttribute('href', `#/teaching?group=${group}`);
  }
  await page.goto(`${base}/#/station?group=data`);
  await page.locator('#station-plan-group').click();
  await expect(page.locator('#teaching-title')).toBeVisible();
  await expect(page.locator('#activity-resource-0')).toHaveValue('EDA');
  await page.locator('#teaching-title').fill('Buổi học kiểm thử nhóm');
  dismissNavigation = true;
  await page.locator('#desk-to-station').click();
  await expect(page.locator('#teaching-title')).toHaveValue('Buổi học kiểm thử nhóm');
  dismissNavigation = false;
  await page.locator('#activity-minutes-0').fill('7');
  await page.locator('details').first().locator('summary').click();
  await page.locator('#activity-note-0').fill('PRIVATE_TEACHER_NOTE_123');
  await page.locator('#teaching-save').click();
  await expect(page.locator('.teaching-status')).toContainText('Đã lưu');
  const saved = await page.evaluate(() => localStorage.getItem('sml.teaching.sessions.v1'));
  const id = JSON.parse(saved).sessions[0].id;
  await page.reload();
  await page.locator(`#teaching-load-${id}`).click();
  await expect(page.locator('#teaching-title')).toHaveValue('Buổi học kiểm thử nhóm');
  await expect(page.locator('#activity-minutes-0')).toHaveValue('7');
  await page.locator('#teaching-title').fill('Bản nháp chưa lưu của tôi');
  const otherTab = await context.newPage();
  await otherTab.goto(base);
  await otherTab.evaluate(() => {
    const value = JSON.parse(localStorage.getItem('sml.teaching.sessions.v1'));
    value.sessions[0].title = 'Bản mới ở tab khác';
    localStorage.setItem('sml.teaching.sessions.v1', JSON.stringify(value));
  });
  await otherTab.close();
  await page.locator('#teaching-save').click();
  await expect(page.getByRole('alert')).toContainText('tab khác');
  await expect(page.locator('#teaching-title')).toHaveValue('Bản nháp chưa lưu của tôi');
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('sml.teaching.sessions.v1')).sessions[0].title), 'Bản mới ở tab khác');
  await page.locator(`#teaching-load-${id}`).click();
  await expect(page.locator('#teaching-title')).toHaveValue('Bản mới ở tab khác');
  await page.evaluate(raw => localStorage.setItem('sml.teaching.sessions.v1', raw), saved);
  await page.locator(`#teaching-load-${id}`).click();
  await expect(page.locator('#teaching-title')).toHaveValue('Buổi học kiểm thử nhóm');
  const downloadText = async (selector, filenamePrefix) => {
    const pending = page.waitForEvent('download');
    await page.locator(selector).click();
    const file = await pending;
    assert.ok(file.suggestedFilename().startsWith(filenamePrefix));
    return fs.readFile(await file.path(), 'utf8');
  };
  const student = await downloadText('#teaching-export-student', 'phieu-nhom');
  assert.ok(!student.includes('PRIVATE'));
  assert.ok(student.includes(`${base}/#/eda?tab=lab`));
  assert.ok(student.includes('47 phút'));
  const teacher = await downloadText('#teaching-export-teacher', 'giao-an');
  assert.ok(teacher.includes('PRIVATE\\_TEACHER\\_NOTE\\_123'));
  const backup = await downloadText('#teaching-backup', 'ban-sao');
  const setImport = async raw => page.locator('#teaching-import').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(raw) });
  await setImport('{"version":999}');
  await expect(page.getByRole('alert')).toContainText('Chưa nhập');
  assert.equal(await page.evaluate(() => localStorage.getItem('sml.teaching.sessions.v1')), saved);
  const invalid = JSON.parse(backup); invalid.sessions[0].activities[0].resourceId = 'javascript:alert(1)';
  await setImport(JSON.stringify(invalid));
  assert.equal(await page.evaluate(() => localStorage.getItem('sml.teaching.sessions.v1')), saved);
  await setImport(backup);
  await expect(page.locator('.teaching-saved li')).toHaveCount(2);
  const copied = await page.evaluate(() => JSON.parse(localStorage.getItem('sml.teaching.sessions.v1')).sessions);
  assert.equal(copied[0].id, id); assert.notEqual(copied[1].id, id);
  await page.locator('#activity-minutes-0').fill('0');
  await page.locator('#teaching-save').click();
  await expect(page.getByRole('alert')).toContainText('Chưa lưu');
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('sml.teaching.sessions.v1')).sessions[0].activities[0].minutes), 7);
  await page.locator('#activity-minutes-0').fill('7');
  await page.locator('#teaching-add').click();
  await expect(page.locator('.teaching-activities > li')).toHaveCount(5);
  await page.locator('#activity-task-4').fill('Thử một thao tác độc lập.');
  await page.locator('#activity-evidence-4').fill('Một nhận xét.');
  await page.locator('#activity-title-4').fill('Hoạt động bổ sung');
  await page.locator('#teaching-up-4').click();
  await expect(page.locator('#activity-title-3')).toHaveValue('Hoạt động bổ sung');
  await page.locator('#teaching-down-3').click();
  await expect(page.locator('#activity-title-4')).toHaveValue('Hoạt động bổ sung');
  await page.locator('#teaching-remove-4').click();
  await expect(page.locator('.teaching-activities > li')).toHaveCount(4);
  await page.locator('#teaching-present').click();
  await expect(page.locator('#runner-title')).toHaveText('Dự đoán trước khi thử');
  await expect(page.locator('.runner-clock')).toHaveText('07:00');
  await expect(page.locator('.activity-runner')).not.toContainText('PRIVATE');
  await expect(page.locator('#runner-resource')).toHaveAttribute('href', '#/eda?tab=lab');
  await expect(page.locator('#runner-prev')).toBeDisabled();
  await page.locator('#runner-toggle').click();
  await expect(page.locator('#runner-toggle')).toHaveText('Tạm dừng');
  await expect(page.locator('.runner-clock')).not.toHaveText('07:00');
  await page.locator('#runner-toggle').click();
  const paused = await page.locator('.runner-clock').innerText();
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('.runner-clock').innerText(), paused);
  await page.locator('#runner-next').click();
  await expect(page.locator('.runner-clock')).toHaveText('25:00');
  await expect(page.locator('#runner-toggle')).toHaveText('Bắt đầu / Tiếp tục');
  await page.locator('#runner-prev').click();
  await expect(page.locator('.runner-clock')).toHaveText('07:00');
  await page.locator('#runner-close').click();
  await expect(page.locator('#teaching-title')).toHaveValue('Buổi học kiểm thử nhóm');
  for (const [width, height] of [[1440,900],[768,1024],[390,844]]) {
    await page.setViewportSize({ width, height });
    for (const route of ['/station?group=dl', '/teaching?group=python']) {
      await page.goto(`${base}/#${route}`);
      await expect(page.locator('h1')).toHaveCount(1);
      if (route.includes('teaching')) {
        await expect(page.locator('#teaching-title')).toBeVisible();
        await expect(page.locator('#activity-resource-0')).toHaveValue('PYTHON');
        await expect(page.locator('#activity-task-1')).toHaveValue(/Colab/);
      } else await expect(page.locator('.station-resources li')).toHaveCount(10);
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${route} overflow ${width}`);
      const ids = await page.locator('[id]').evaluateAll(elements => elements.map(e => e.id));
      assert.equal(new Set(ids).size, ids.length);
      await page.screenshot({ path: `/tmp/sml-station-${route.startsWith('/station') ? 'hub' : 'desk'}-${width}.png`, fullPage: true });
    }
    await page.locator('#teaching-present').click();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: `/tmp/sml-station-runner-${width}.png` });
  }
  const blocked = await browser.newContext();
  await blocked.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error('Storage blocked'); }; });
  const blockedPage = await blocked.newPage();
  await blockedPage.goto(`${base}/#/teaching`);
  await blockedPage.locator('#teaching-save').click();
  await expect(blockedPage.getByRole('alert')).toContainText('Chưa lưu');
  await expect(blockedPage.locator('#teaching-title')).toHaveValue(/Buổi thực hành/);
  await blocked.close();
  const corrupt = await browser.newContext();
  const corruptPage = await corrupt.newPage();
  await corruptPage.goto(base);
  await corruptPage.evaluate(() => localStorage.setItem('sml.teaching.sessions.v1', 'BROKEN_DO_NOT_OVERWRITE'));
  await corruptPage.goto(`${base}/#/teaching`);
  await expect(corruptPage.getByRole('alert')).toContainText('Không đọc được');
  await corruptPage.locator('#teaching-save').click();
  assert.equal(await corruptPage.evaluate(() => localStorage.getItem('sml.teaching.sessions.v1')), 'BROKEN_DO_NOT_OVERWRITE');
  await expect(corruptPage.locator('#teaching-allow-recovery')).toBeDisabled();
  const rawDownload = corruptPage.waitForEvent('download');
  await corruptPage.locator('#teaching-export-raw').click();
  assert.equal(await fs.readFile(await (await rawDownload).path(), 'utf8'), 'BROKEN_DO_NOT_OVERWRITE');
  await corruptPage.locator('#teaching-allow-recovery').check();
  await corruptPage.locator('#teaching-import').setInputFiles({ name: 'restored.json', mimeType: 'application/json', buffer: Buffer.from(backup) });
  await expect(corruptPage.locator('.teaching-status')).toContainText('Đã thêm 1 bản sao');
  await expect(corruptPage.locator('.teaching-saved li')).toHaveCount(1);
  await corruptPage.reload();
  await expect(corruptPage.getByRole('alert')).toHaveCount(0);
  await corrupt.close();
  assert.deepEqual(errors, []); assert.deepEqual(failed, []); assert.deepEqual(external, []);
  console.log('PASS teaching station: group coverage, real routes, editable plan, save/reload, private notes, Markdown/JSON export, atomic import/copy, validation, reorder, runner/timer, 3 viewports, blocked/corrupt storage preservation; no page/network errors.');
} finally { await browser.close(); }
